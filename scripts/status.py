"""Write STATUS.md from the mark colors in both masters.

The release target is every glyph green in both masters. This script reads
the UFO sources on disk and reports the glyphs that are not green, by script
and master. It reads nothing else. Do not edit STATUS.md by hand.

    .venv/bin/python scripts/status.py          rewrite STATUS.md
    .venv/bin/python scripts/status.py --print  print to stdout only
"""

import datetime
import json
import plistlib
import sys
import tomllib
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MASTERS = ['Regular', 'Bold']
OUT = ROOT / 'STATUS.md'
SCRIPTS = ['Arabic', 'Hebrew', 'Latin and other']
COLORS = tomllib.loads((ROOT / 'sources/design.toml').read_text())['colors']


def color_name(value):
    if not value:
        return 'none'
    rgba = [float(part) for part in value.split(',')]
    for name, record in COLORS.items():
        for known in record.get('rgba', []):
            if all(abs(a - b) < 0.011 for a, b in zip(rgba, known)):
                return name
    return 'unknown'


def script_of(name):
    if '-ar' in name:
        return 'Arabic'
    if '-hb' in name:
        return 'Hebrew'
    return 'Latin and other'


def read_master(master):
    ufo = ROOT / f'sources/VirtuaGrotesk-{master}.ufo'
    contents = plistlib.loads((ufo / 'glyphs/contents.plist').read_bytes())
    glyphs = {}
    for name, filename in contents.items():
        root = ET.parse(ufo / 'glyphs' / filename).getroot()
        outline = root.find('outline')
        contours = len(outline.findall('contour')) if outline is not None else 0
        mark = None
        lib = root.find('lib/dict')
        if lib is not None:
            children = list(lib)
            for key, value in zip(children, children[1:]):
                if key.tag == 'key' and key.text == 'public.markColor':
                    mark = value.text
        glyphs[name] = dict(color=color_name(mark),
                            kind='contour' if contours else 'composite or empty')
    return glyphs


def report():
    data = {master: read_master(master) for master in MASTERS}
    today = datetime.date.today().isoformat()
    lines = ['# Status', '',
             f'Generated by `scripts/status.py` on {today} from the mark colors in',
             'both masters. The release target is every glyph green in both masters.',
             'Do not edit this file by hand.', '',
             '| Master | Script | Kind | Green | Not green |',
             '| --- | --- | --- | ---: | ---: |']
    pending = {}
    for master in MASTERS:
        for script in SCRIPTS:
            for kind in ['contour', 'composite or empty']:
                rows = {n: g for n, g in data[master].items()
                        if script_of(n) == script and g['kind'] == kind}
                green = sum(1 for g in rows.values() if g['color'] == 'green')
                lines.append(f'| {master} | {script} | {kind} | {green} | {len(rows) - green} |')
                for name, glyph in rows.items():
                    if glyph['color'] != 'green':
                        pending.setdefault((master, script, kind), {}).setdefault(
                            glyph['color'], []).append(name)
    total = sum(len(g) for g in data.values())
    green = sum(1 for g in data.values() for x in g.values() if x['color'] == 'green')
    lines += ['', f'Total: {green} of {total} master glyphs are green.', '',
              '## Glyphs not green', '']
    for (master, script, kind), colors in pending.items():
        lines.append(f'### {master}, {script}, {kind}')
        lines.append('')
        for color in sorted(colors):
            names = ', '.join(f'`{n}`' for n in sorted(colors[color]))
            lines.append(f'- {color} ({len(colors[color])}): {names}')
        lines.append('')
    return '\n'.join(lines)


if __name__ == '__main__':
    text = report()
    if '--print' in sys.argv:
        print(text)
    else:
        OUT.write_text(text)
        print(text.split('## Glyphs not green')[0])
